use std::fs;

fn temp_dir(name: &str) -> std::path::PathBuf {
    let dir =
        std::env::temp_dir().join(format!("godothub-identity-{}-{}", name, std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    dir
}

#[test]
fn marker_is_written_inside_the_project_folder() {
    let dir = temp_dir("inside");
    fs::create_dir_all(&dir).unwrap();
    let path = dir.to_string_lossy().to_string();

    assert!(super::write_project_identity(&path, "abc-123", None));
    assert!(super::identity_file(&path).exists());
    assert_eq!(
        super::read_project_identity(&path).as_deref(),
        Some("abc-123")
    );

    fs::remove_dir_all(&dir).ok();
}

#[test]
fn marker_explains_what_it_is() {
    let dir = temp_dir("header");
    fs::create_dir_all(&dir).unwrap();
    let path = dir.to_string_lossy().to_string();

    assert!(super::write_project_identity(&path, "abc-123", None));
    let raw = fs::read_to_string(super::identity_file(&path)).unwrap();
    assert!(
        raw.starts_with("{\n  \"//\":"),
        "expected a leading self-describing entry, got: {raw}"
    );
    assert!(raw.contains("Generated by GodotHub"));

    fs::remove_dir_all(&dir).ok();
}

#[test]
fn category_round_trips_and_survives_a_folder_rename() {
    let base = temp_dir("category");
    let original = base.join("Original");
    fs::create_dir_all(&original).unwrap();
    let original_path = original.to_string_lossy().to_string();

    assert!(super::write_project_identity(
        &original_path,
        "stable-id",
        Some("Game Jams")
    ));
    assert_eq!(
        super::read_project_category(&original_path).as_deref(),
        Some("Game Jams")
    );

    let renamed = base.join("Renamed");
    fs::rename(&original, &renamed).unwrap();
    let renamed_path = renamed.to_string_lossy().to_string();

    assert_eq!(
        super::read_project_identity(&renamed_path).as_deref(),
        Some("stable-id")
    );
    assert_eq!(
        super::read_project_category(&renamed_path).as_deref(),
        Some("Game Jams")
    );

    fs::remove_dir_all(&base).ok();
}

