use std::fs;

fn temp_dir(name: &str) -> std::path::PathBuf {
    let dir =
        std::env::temp_dir().join(format!("godothub-godotrc-{}-{}", name, std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn the_generated_header_does_not_hide_the_version() {
    let dir = temp_dir("parse");
    let raw = "# Generated by GodotHub. This file pins the Godot version for this project.\n\
               # GodotHub reads the first non-comment line below.\n\
               4.3.1-stable no-dotnet\n";
    fs::write(dir.join(".godotrc"), raw).unwrap();

    let detected = super::parse_godotrc(&dir.join(".godotrc")).expect("version detected");
    assert_eq!(detected.number.major, 4);
    assert_eq!(detected.number.minor, 3);
    assert_eq!(detected.number.patch, 1);
    assert!(!detected.is_dotnet);

    fs::remove_dir_all(&dir).ok();
}

#[test]
fn a_pinned_godotrc_round_trips_through_its_header() {
    let dir = temp_dir("write");
    let number = super::parse_installed_tag("4.4-stable").expect("parse tag");

    super::write_godotrc_pin(&dir, &number).expect("write pin");

    let raw = fs::read_to_string(crate::project_metadata::version_file(&dir)).unwrap();
    assert!(
        raw.starts_with("# Generated by GodotHub"),
        "expected a self-describing header, got: {raw}"
    );

    let detected =
        super::parse_godotrc(&crate::project_metadata::version_file(&dir)).expect("read back");
    assert_eq!(detected.number.major, 4);
    assert_eq!(detected.number.minor, 4);
    assert!(!detected.is_dotnet);

    fs::remove_dir_all(&dir).ok();
}

#[test]
fn legacy_pin_migrates_is_detected_and_can_be_replaced_or_switched_to_mono() {
    let dir = temp_dir("migration");
    fs::write(dir.join(".godotrc"), "4.3-stable no-dotnet\n").unwrap();
    let path = dir.to_string_lossy();
    let version = super::detect_version(&path).unwrap();
    assert_eq!(super::release_string(&version.number), "4.3-stable");
    assert!(!dir.join(".godotrc").exists());
    assert!(crate::project_metadata::version_file(&dir).exists());
    super::pin_version(&path, "4.4-stable", false).unwrap();
    assert_eq!(
        super::release_string(&super::detect_version(&path).unwrap().number),
        "4.4-stable"
    );
    super::pin_version(&path, "4.5-stable-mono", false).unwrap();
    assert!(!crate::project_metadata::version_file(&dir).exists());
    assert!(dir.join("global.json").exists());
    let version = super::detect_version(&path).unwrap();
    assert!(version.is_dotnet);
    assert_eq!(super::release_string(&version.number), "4.5-stable");
    fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn ancestor_version_pins_still_work_without_migrating_parent_folders() {
    let dir = temp_dir("ancestor");
    fs::write(dir.join(".godotrc"), "4.4-stable no-dotnet\n").unwrap();
    let child = dir.join("child");
    fs::create_dir(&child).unwrap();
    assert_eq!(
        super::release_string(
            &super::detect_version(&child.to_string_lossy())
                .unwrap()
                .number
        ),
        "4.4-stable"
    );
    assert!(dir.join(".godotrc").exists());
    fs::remove_dir_all(&dir).unwrap();
}
