use std::fs;

fn temp_dir(name: &str) -> std::path::PathBuf {
    let dir =
        std::env::temp_dir().join(format!("godothub-godotrc-{}-{}", name, std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn the_generated_header_does_not_hide_the_version() {
    let dir = temp_dir("parse");
    let raw = "# Generated by GodotHub. This file pins the Godot version for this project.\n\
               # GodotHub reads the first non-comment line below.\n\
               4.3.1-stable no-dotnet\n";
    fs::write(dir.join(".godotrc"), raw).unwrap();

    let detected = super::parse_godotrc(&dir.join(".godotrc")).expect("version detected");
    assert_eq!(detected.number.major, 4);
    assert_eq!(detected.number.minor, 3);
    assert_eq!(detected.number.patch, 1);
    assert!(!detected.is_dotnet);

    fs::remove_dir_all(&dir).ok();
}

#[test]
fn a_pinned_godotrc_round_trips_through_its_header() {
    let dir = temp_dir("write");
    let number = super::parse_installed_tag("4.4-stable").expect("parse tag");

    super::write_godotrc_pin(&dir, &number).expect("write pin");

    let raw = fs::read_to_string(dir.join(".godotrc")).unwrap();
    assert!(
        raw.starts_with("# Generated by GodotHub"),
        "expected a self-describing header, got: {raw}"
    );

    let detected = super::parse_godotrc(&dir.join(".godotrc")).expect("read back");
    assert_eq!(detected.number.major, 4);
    assert_eq!(detected.number.minor, 4);
    assert!(!detected.is_dotnet);

    fs::remove_dir_all(&dir).ok();
}
