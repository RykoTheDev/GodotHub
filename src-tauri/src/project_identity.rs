use crate::persist;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

use crate::project_metadata;
pub use crate::project_metadata::IDENTITY_FILE;

const IDENTITY_COMMENT: &str = "Generated by GodotHub. Do not edit. This marker identifies the project so its time tracking and category follow the folder when it is renamed or moved.";

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
struct ProjectIdentity {
    #[serde(rename = "//", default, skip_serializing_if = "String::is_empty")]
    comment: String,
    #[serde(default)]
    id: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    category: Option<String>,
}

pub fn identity_file(project_path: &str) -> PathBuf {
    project_metadata::directory(Path::new(project_path)).join(IDENTITY_FILE)
}

fn normalize_category(category: Option<&str>) -> Option<String> {
    category
        .map(str::trim)
        .filter(|c| !c.is_empty())
        .map(str::to_string)
}

fn read_identity(project_path: &str) -> Option<ProjectIdentity> {
    let root = Path::new(project_path);
    let _ = project_metadata::migrate(root);
    persist::read_json_opt::<ProjectIdentity>(&identity_file(project_path))
        .filter(|identity| !identity.id.trim().is_empty())
        .or_else(|| persist::read_json_opt(&root.join(project_metadata::LEGACY_IDENTITY_FILE)))
}

pub fn read_project_identity(project_path: &str) -> Option<String> {
    let identity = read_identity(project_path)?;
    let id = identity.id.trim();
    if id.is_empty() {
        None
    } else {
        Some(id.to_string())
    }
}

pub fn read_project_category(project_path: &str) -> Option<String> {
    read_identity(project_path)
        .and_then(|identity| normalize_category(identity.category.as_deref()))
}

pub fn write_project_identity(project_path: &str, id: &str, category: Option<&str>) -> bool {
    let root = Path::new(project_path);
    let _ = project_metadata::migrate(root);
    if project_metadata::prepare(root).is_err() {
        return false;
    }
    let identity = ProjectIdentity {
        comment: IDENTITY_COMMENT.to_string(),
        id: id.to_string(),
        category: normalize_category(category),
    };
    let path = identity_file(project_path);
    if persist::write_json(&path, &identity).is_err() {
        return false;
    }
    project_metadata::hide(&path);
    true
}

pub fn ensure_project_identity(project_path: &str, id: &str, category: Option<&str>) -> bool {
    let wanted = normalize_category(category);
    if let Some(existing) = read_identity(project_path) {
        if existing.id == id && existing.comment == IDENTITY_COMMENT && existing.category == wanted
        {
            if !identity_file(project_path).is_file() {
                return write_project_identity(project_path, id, wanted.as_deref());
            }
            project_metadata::hide(&identity_file(project_path));
            return true;
        }
    }
    write_project_identity(project_path, id, wanted.as_deref())
}