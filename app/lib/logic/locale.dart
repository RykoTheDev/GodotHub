enum GhDatePart { numeric, twoDigit, narrow, short, long }

class GhDateFormatOptions {
  const GhDateFormatOptions({this.weekday, this.year, this.month, this.day, this.hour, this.minute, this.second});

  final GhDatePart? weekday;
  final GhDatePart? year;
  final GhDatePart? month;
  final GhDatePart? day;
  final GhDatePart? hour;
  final GhDatePart? minute;
  final GhDatePart? second;

  bool get _hasDate => weekday != null || year != null || month != null || day != null;
  bool get _hasTime => hour != null || minute != null || second != null;

  static const _defaultDate = GhDateFormatOptions(year: GhDatePart.numeric, month: GhDatePart.numeric, day: GhDatePart.numeric);
  static const _defaultTime = GhDateFormatOptions(hour: GhDatePart.numeric, minute: GhDatePart.twoDigit, second: GhDatePart.twoDigit);
}

String formatLocaleDate(DateTime date, [GhDateFormatOptions? options, String? locale]) {
  final opts = options ?? GhDateFormatOptions._defaultDate;
  final withDate = opts._hasDate ? opts : _merge(GhDateFormatOptions._defaultDate, opts);
  return _formatWith(date.toLocal(), withDate, locale ?? uiLocale());
}

String formatLocaleDateTime(DateTime date, [GhDateFormatOptions? options, String? locale]) {
  final all = _merge(GhDateFormatOptions._defaultDate, GhDateFormatOptions._defaultTime);
  final opts = options ?? all;
  return _formatWith(date.toLocal(), opts._hasDate || opts._hasTime ? opts : all, locale ?? uiLocale());
}

GhDateFormatOptions _merge(GhDateFormatOptions a, GhDateFormatOptions b) => GhDateFormatOptions(
  weekday: b.weekday ?? a.weekday,
  year: b.year ?? a.year,
  month: b.month ?? a.month,
  day: b.day ?? a.day,
  hour: b.hour ?? a.hour,
  minute: b.minute ?? a.minute,
  second: b.second ?? a.second,
);

const _knownSkeletons = {
  'd', 'E', 'EEEE', 'LLL', 'LLLL', 'M', 'Md', 'MEd', 'MMM', 'MMMd', 'MMMEd', 'MMMM', 'MMMMd', 'MMMMEEEEd', 'y', 'yM',
  'yMd', 'yMEd', 'yMMM', 'yMMMd', 'yMMMEd', 'yMMMM', 'yMMMMd', 'yMMMMEEEEd',
};

final _meridiem = RegExp(r'([ap])\.[\s\u00a0\u202f]*m\.');

String _formatWith(DateTime date, GhDateFormatOptions options, String language) {
  final locale = ghIntlLocale(language);
  final tag = language.replaceAll('_', '-').toLowerCase();
  var datePattern = options._hasDate ? _datePattern(options, locale) : null;
  final timePattern = options._hasTime ? _timePattern(options, locale, twentyFourHour: tag == 'ar-ma') : null;
  if (datePattern != null && tag == 'ar-ma') {
    final month = ghMonthNames(language)[date.month - 1];
    datePattern = _replaceUnquoted(datePattern, RegExp('[ML]{3,}'), "'$month'");
  }
  final dateText = datePattern == null ? null : DateFormat(datePattern, locale).format(date);
  var timeText = timePattern == null ? null : DateFormat(timePattern, locale).format(date);
  if (timeText != null && tag == 'es-mx') {
    timeText = timeText.replaceAllMapped(_meridiem, (m) => '${m[1]}.m.');
  }
  final String text;
  if (dateText == null || timeText == null) {
    text = dateText ?? timeText ?? '';
  } else {
    final glue = tag == 'pt-br' ? '{1}, {0}' : _unquote(DateFormat('y', locale).dateSymbols.DATETIMEFORMATS[3]);
    text = glue.replaceAll('{1}', dateText).replaceAll('{0}', timeText);
  }
  return text.replaceAll('\u202f', ' ');
}

String _unquote(String pattern) => pattern.split("''").map((part) => part.replaceAll("'", '')).join("'");

String _replaceUnquoted(String pattern, RegExp token, String replacement) {
  final parts = pattern.split("'");
  for (var i = 0; i < parts.length; i += 2) {
    parts[i] = parts[i].replaceAll(token, replacement);
  }
  return parts.join("'");
}

String _datePattern(GhDateFormatOptions o, String locale) {
  final onlyMonth = o.month != null && o.year == null && o.day == null && o.weekday == null;
  final month = switch (o.month) {
    null => '',
    GhDatePart.numeric || GhDatePart.twoDigit => 'M',
    GhDatePart.short || GhDatePart.narrow => onlyMonth ? 'LLL' : 'MMM',
    GhDatePart.long => onlyMonth ? 'LLLL' : 'MMMM',
  };
  final textMonth = o.month == GhDatePart.long || o.month == GhDatePart.short || o.month == GhDatePart.narrow;
  var weekday = switch (o.weekday) {
    null => '',
    GhDatePart.long => 'EEEE',
    _ => 'E',
  };
  final year = o.year == null ? '' : 'y';
  final day = o.day == null ? '' : 'd';
  var skeleton = '$year$month$weekday$day';
  if (!_knownSkeletons.contains(skeleton) && weekday.isNotEmpty) {
    weekday = o.month == GhDatePart.long ? 'EEEE' : 'E';
    skeleton = '$year$month$weekday$day';
  }
  if (!_knownSkeletons.contains(skeleton) && weekday.isNotEmpty && !textMonth) {
    skeleton = '${year}ME$day';
  }
  if (!_knownSkeletons.contains(skeleton)) {
    skeleton = weekday.isNotEmpty ? 'yMMMEd' : 'yMd';
  }
  var pattern = DateFormat(skeleton, locale).pattern ?? skeleton;
  if (o.day == GhDatePart.twoDigit) {
    pattern = _widen(pattern, 'd');
  }
  if (o.month == GhDatePart.twoDigit) {
    pattern = _widen(pattern, 'M');
  }
  if (o.year == GhDatePart.twoDigit) {
    pattern = _replaceUnquoted(pattern, RegExp('y+'), 'yy');
  }
  return pattern;
}

String _timePattern(GhDateFormatOptions o, String locale, {bool twentyFourHour = false}) {
  final hour = twentyFourHour ? 'H' : 'j';
  final skeleton = o.hour != null
      ? (o.minute != null ? (o.second != null ? '${hour}ms' : '${hour}m') : hour)
      : (o.minute != null ? (o.second != null ? 'ms' : 'm') : 's');
  var pattern = DateFormat(skeleton, locale).pattern ?? skeleton;
  if (o.hour == GhDatePart.twoDigit) {
    pattern = _widen(_widen(pattern, 'h'), 'H');
  }
  return pattern;
}

String _widen(String pattern, String letter) {
  final out = StringBuffer();
  var quoted = false;
  for (var i = 0; i < pattern.length; i++) {
    final c = pattern[i];
    if (c == "'") {
      quoted = !quoted;
      out.write(c);
      continue;
    }
    final single = !quoted &&
        c == letter &&
        (i == 0 || pattern[i - 1] != letter) &&
        (i == pattern.length - 1 || pattern[i + 1] != letter);
    out.write(single ? '$c$c' : c);
  }
  return out.toString();
}

int ghLocaleCompare(String a, String b) {
  if (identical(a, b) || a == b) {
    return 0;
  }
  final x = _collationElements(a);
  final y = _collationElements(b);
  for (final level in const [0, 1, 2]) {
    final result = _compareLevel(x, y, level);
    if (result != 0) {
      return result;
    }
  }
  return 0;
}

int _compareLevel(List<_Ce> x, List<_Ce> y, int level) {
  var i = 0;
  var j = 0;
  while (true) {
    while (i < x.length && level == 0 && x[i].primary == 0) {
      i++;
    }
    while (j < y.length && level == 0 && y[j].primary == 0) {
      j++;
    }
    if (i >= x.length || j >= y.length) {
      return (i >= x.length ? 0 : 1) - (j >= y.length ? 0 : 1);
    }
    final a = x[i].level(level);
    final b = y[j].level(level);
    if (a != b) {
      return a < b ? -1 : 1;
    }
    i++;
    j++;
  }
}

class _Ce {
  const _Ce(this.primary, this.secondary, this.tertiary);

  final int primary;
  final int secondary;
  final int tertiary;

  int level(int level) => switch (level) {
    0 => primary,
    1 => secondary,
    _ => tertiary,
  };
}

const _primaryStride = 0x110000;
const _markStride = 1024;
const _caseStride = 16;
const _expansionSecondary = 200 * _markStride;

enum _Decomposition { canonical, compat, expansion }

class _CollationTable {
  _CollationTable() {
    for (var i = 0; i < _collationMarks.length; i++) {
      marks[_collationMarks[i]] = (i + 1) * _markStride;
    }
    final slots = <int, int>{};
    for (var i = 0; i < _collationVariants.length; i += 2) {
      slots[_collationVariants[i]] = _collationVariants[i + 1];
    }
    var p = 0;
    var s = 0;
    var t = 0;
    for (final value in _collationOrder) {
      switch (value) {
        case -1:
          p++;
          s = 0;
          t = 0;
        case -2:
          s++;
          t = 0;
        case -3:
          t++;
        case -4:
          break;
        default:
          final slot = slots[value];
          final secondary = slot == null
              ? 0
              : slot.isOdd
                  ? (slot ~/ 2 + 1) * _markStride
                  : (slot ~/ 2) * _markStride + _markStride ~/ 2 + s;
          singles[value] = _Ce(p * _primaryStride, secondary, t * _caseStride);
      }
    }
    maxPrimary = (p + 1) * _primaryStride;
    for (var i = 0; i < _collationAnchors.length; i += 3) {
      anchors.add((_collationAnchors[i], _collationAnchors[i + 1], singles[_collationAnchors[i + 2]]!.primary));
    }
    var i = 0;
    while (i < _collationDecompositions.length) {
      final cp = _collationDecompositions[i];
      final count = _collationDecompositions[i + 1];
      final kind = count <= -100
          ? _Decomposition.expansion
          : count < 0
              ? _Decomposition.compat
              : _Decomposition.canonical;
      final length = kind == _Decomposition.expansion ? -count - 100 : count.abs();
      decompositions[cp] = (_collationDecompositions.sublist(i + 2, i + 2 + length), kind);
      i += 2 + length;
    }
  }

  final Map<int, int> marks = {};
  final Map<int, _Ce> singles = {};
  final Map<int, (List<int>, _Decomposition)> decompositions = {};
  late final int maxPrimary;
  final List<(int, int, int)> anchors = [];

  void append(int rune, List<_Ce> out, {int tertiaryBoost = 0}) {
    for (final (start, end, primary) in anchors) {
      if (rune >= start && rune <= end) {
        out.add(_Ce(primary + rune - start + 1, 0, tertiaryBoost));
        return;
      }
    }
    final mark = marks[rune];
    if (mark != null) {
      out.add(_Ce(0, mark, 0));
      return;
    }
    final single = singles[rune];
    if (single != null) {
      out.add(tertiaryBoost == 0 ? single : _Ce(single.primary, single.secondary, single.tertiary + tertiaryBoost));
      return;
    }
    final decomposition = decompositions[rune];
    if (decomposition != null) {
      final (parts, kind) = decomposition;
      final boost = switch (kind) {
        _Decomposition.canonical => 0,
        _Decomposition.compat => rune >= 0xFF01 && rune <= 0xFF5E ? 1 : 2,
        _Decomposition.expansion => 2,
      };
      for (var i = 0; i < parts.length; i++) {
        append(parts[i], out, tertiaryBoost: tertiaryBoost + boost);
        if (i == 0 && kind == _Decomposition.expansion) {
          out.add(const _Ce(0, _expansionSecondary, 0));
        }
      }
      return;
    }
    if (_isIgnorable(rune)) {
      return;
    }
    out.add(_Ce(maxPrimary + rune, 0, tertiaryBoost));
  }
}

bool _isIgnorable(int rune) =>
    rune < 0x20 ||
    rune == 0x7F ||
    (rune >= 0x80 && rune < 0xA0) ||
    rune == 0xAD ||
    rune == 0x488 ||
    rune == 0x489 ||
    rune == 0x640 ||
    (rune >= 0x200B && rune <= 0x200F) ||
    (rune >= 0x202A && rune <= 0x202E) ||
    (rune >= 0x2060 && rune <= 0x206F) ||
    (rune >= 0xFE00 && rune <= 0xFE0F) ||
    rune == 0xFEFF;

final _collation = _CollationTable();

List<_Ce> _collationElements(String text) {
  final out = <_Ce>[];
  for (final rune in text.runes) {
    _collation.append(rune, out);
  }
  return out;
}

